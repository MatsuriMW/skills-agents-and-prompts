import os
import json
from openai import OpenAI

client = OpenAI(api_key=os.getenv("OPENAI_API_KEY"))

FEW_SHOT_EXAMPLE = """
【示例输入】
价格数据：近期振幅较大，换手率偏高；财务数据：PE 45倍，负债率 68%，利润增速 -5%

【示例思考过程（COT）】
估值风险：PE 45倍显著高于行业均值（约25倍），安全边际不足 → 高风险
政策风险：无特殊政策敏感性，属于消费行业 → 低风险
流动性风险：换手率偏高说明筹码不稳定，大幅波动时流动性可能骤降 → 中风险
盈利风险：利润增速转负(-5%)，基本面出现恶化信号 → 高风险
综合：两项高风险，整体评级"较高风险"，建议控制仓位。

【示例输出】

## 六、风险评估

```mermaid
pie title 风险权重分布
    "估值风险" : 35
    "政策风险" : 10
    "流动性风险" : 20
    "盈利风险" : 35
```

| 风险类型 | 等级 | 核心依据 | 应对建议 |
|----------|------|----------|----------|
| 📈 估值风险 | 🔴 高 | PE 45倍远超行业均值，泡沫风险较大 | 等待估值回调后再介入 |
| 📋 政策风险 | 🟢 低 | 消费行业政策支持，无明显管控风险 | 持续跟踪行业政策动态 |
| 💧 流动性风险 | 🟡 中 | 换手率偏高，市场情绪主导明显 | 避免追高，设好止损位 |
| 💰 盈利风险 | 🔴 高 | 利润增速转负，盈利趋势恶化 | 关注下季度财报，谨慎持仓 |

### 综合风险评级

**整体风险：⚠️ 较高风险**

估值偏贵叠加盈利下滑，当前风险收益比不佳。建议观望为主，待盈利企稳或估值合理后再考虑布局。
"""

def risk_analysis(data):
    prompt = f"""你是专业的A股风险分析师，擅长识别投资风险和量化风险等级。

{FEW_SHOT_EXAMPLE}

---

现在请分析以下真实数据，严格按照示例格式输出风险报告。

【原始数据】
{json.dumps(data, ensure_ascii=False, indent=2)}

【Chain of Thought 分析步骤】
第一步（估值风险）：结合价格波动和财务数据，判断当前估值是否合理，安全边际如何
第二步（政策风险）：根据行业属性推断政策敏感性，是否面临监管或行业整顿风险
第三步（流动性风险）：分析成交量、换手率等指标，评估流动性稳定程度
第四步（盈利风险）：评估营收和利润趋势，判断盈利可持续性和下行风险

风险等级标准：
- 🔴 高：需要重点关注，可能显著影响投资回报
- 🟡 中：存在一定风险，需要持续监控
- 🟢 低：风险可控，对投资影响有限

【输出要求】
- 严格按示例 Markdown 结构输出（从 ## 六 开始）
- pie 图中四项权重之和必须为 100
- 不输出任何额外说明，直接从 ## 六 开始
"""

    res = client.chat.completions.create(
        model="gpt-4o-mini",
        messages=[{"role": "user", "content": prompt}]
    )

    return res.choices[0].message.content

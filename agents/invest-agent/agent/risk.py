import json
from openai import OpenAI

from config import OPENAI_API_KEY, OPENAI_MODEL

client = OpenAI(api_key=OPENAI_API_KEY)

FEW_SHOT_EXAMPLE = """
【示例输入】
已算好的指标：区间涨跌幅 +18%，收盘在区间的位置 92%，年化波动率 48%，平均换手率 6.5%；财务数据：负债率 68%，利润增速 -5%（数据里没有 PE/PB）

【示例思考过程（COT）】
估值风险：数据里没有 PE/PB，没法直接判断贵不贵；只能看到 30 日涨了 18%、收盘在区间 92% 的高位，短期追高风险偏大 → 中（推断）
政策风险：数据未提供行业和政策信息，按公司属性推断，无明显政策敏感性 → 低（推断）
流动性风险：换手率 6.5%、年化波动 48%，筹码不稳定，大幅波动时流动性可能骤降 → 中风险
盈利风险：利润增速转负(-5%)，基本面出现恶化信号 → 高风险
综合：盈利一项高风险，估值和流动性中风险，整体评级"较高风险"，建议控制仓位。

【示例输出】

## 六、风险评估

```mermaid
pie title 风险权重分布
    "估值风险" : 35
    "政策风险" : 10
    "流动性风险" : 20
    "盈利风险" : 35
```

| 风险类型 | 等级 | 核心依据 | 应对建议 |
|----------|------|----------|----------|
| 📈 估值风险 | 🟡 中（推断） | 数据未提供 PE/PB；30 日涨 18%，处在区间高位 | 补充估值数据后再判断，避免追高 |
| 📋 政策风险 | 🟢 低（推断） | 数据未提供政策信息，按行业属性推断 | 持续跟踪行业政策动态 |
| 💧 流动性风险 | 🟡 中 | 换手率 6.5%、年化波动 48%，情绪主导明显 | 设好止损位 |
| 💰 盈利风险 | 🔴 高 | 利润增速转负，盈利趋势恶化 | 关注下季度财报，谨慎持仓 |

### 综合风险评级

**整体风险：⚠️ 较高风险**

短期涨幅大叠加盈利下滑，当前风险收益比不佳。建议观望为主，待盈利企稳或估值合理后再考虑布局。
"""

def risk_analysis(data):
    prompt = f"""你是专业的A股风险分析师，擅长识别投资风险和量化风险等级。

{FEW_SHOT_EXAMPLE}

---

现在请分析以下真实数据，严格按照示例格式输出风险报告。

【原始数据】
{json.dumps(data, ensure_ascii=False, indent=2)}

【关于数据】
- 「已算好的指标」是程序算出来的，直接引用，不要自己重算
- 数据里没有 PE/PB、行业均值、政策和新闻。用到这些时写「数据未提供」，等级后面标「（推断）」，不要编数字

【Chain of Thought 分析步骤】
第一步（估值风险）：结合价格波动和财务数据，判断当前估值是否合理，安全边际如何
第二步（政策风险）：根据行业属性推断政策敏感性，是否面临监管或行业整顿风险
第三步（流动性风险）：分析成交量、换手率等指标，评估流动性稳定程度
第四步（盈利风险）：评估营收和利润趋势，判断盈利可持续性和下行风险

风险等级标准：
- 🔴 高：需要重点关注，可能显著影响投资回报
- 🟡 中：存在一定风险，需要持续监控
- 🟢 低：风险可控，对投资影响有限

【输出要求】
- 严格按示例 Markdown 结构输出（从 ## 六 开始）
- pie 图中四项权重之和必须为 100
- 不输出任何额外说明，直接从 ## 六 开始
"""

    res = client.chat.completions.create(
        model=OPENAI_MODEL,
        messages=[{"role": "user", "content": prompt}]
    )

    return res.choices[0].message.content
